import csv
import io
import json
import os

from fastapi import APIRouter, Depends
from fastapi.responses import StreamingResponse
from sqlalchemy.orm import Session

from app import models, schemas
from app.audit import log_action
from app.config import settings
from app.database import get_db
from app.security import get_current_user, require_roles

router = APIRouter(prefix="/reports", tags=["Reporting"])


@router.get("/summary", response_model=schemas.ReportSummary)
def report_summary(db: Session = Depends(get_db), user: models.User = Depends(get_current_user)):
    total_events = db.query(models.SecurityEvent).count()
    total_threats = db.query(models.DetectionResult).filter(models.DetectionResult.random_forest_prediction == 1).count()

    severity_distribution = {
        sev: db.query(models.DetectionResult).filter(models.DetectionResult.severity == sev).count()
        for sev in ("critical", "high", "medium", "low")
    }
    total_alerts = db.query(models.Alert).count()
    total_incidents = db.query(models.Incident).count()
    incident_status_breakdown = {
        s: db.query(models.Incident).filter(models.Incident.status == s).count()
        for s in ("open", "investigating", "escalated", "resolved", "closed")
    }

    eval_path = os.path.join(settings.ML_MODELS_DIR, "evaluation_results.json")
    evaluation_metrics = None
    if os.path.exists(eval_path):
        with open(eval_path) as f:
            evaluation_metrics = json.load(f)

    model_info = {
        "random_forest_trained": os.path.exists(os.path.join(settings.ML_MODELS_DIR, "random_forest_model.joblib")),
        "isolation_forest_trained": os.path.exists(os.path.join(settings.ML_MODELS_DIR, "isolation_forest_model.joblib")),
    }

    log_action(db, user.id, "report_generated", f"Summary report generated by '{user.username}'")

    return schemas.ReportSummary(
        total_events=total_events, total_threats_detected=total_threats,
        severity_distribution=severity_distribution, total_alerts=total_alerts,
        total_incidents=total_incidents, incident_status_breakdown=incident_status_breakdown,
        model_info=model_info, evaluation_metrics=evaluation_metrics,
    )


@router.get("/export/csv")
def export_csv(db: Session = Depends(get_db), user: models.User = Depends(get_current_user)):
    alerts = db.query(models.Alert).order_by(models.Alert.created_at.desc()).all()
    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow(["id", "title", "severity", "risk_score", "status", "created_at"])
    for a in alerts:
        writer.writerow([a.id, a.title, a.severity, a.risk_score, a.status, a.created_at])
    buf.seek(0)
    log_action(db, user.id, "report_export_csv", f"CSV alert export generated by '{user.username}'")
    return StreamingResponse(
        iter([buf.getvalue()]), media_type="text/csv",
        headers={"Content-Disposition": "attachment; filename=alerts_report.csv"},
    )


@router.get("/export/pdf")
def export_pdf(db: Session = Depends(get_db), user: models.User = Depends(get_current_user)):
    from fpdf import FPDF

    summary = report_summary(db, user)
    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 16)
    pdf.cell(0, 10, "Telemedicine IDS - Security Report", ln=True)
    pdf.set_font("Helvetica", size=11)
    pdf.ln(5)
    pdf.cell(0, 8, f"Total events: {summary.total_events}", ln=True)
    pdf.cell(0, 8, f"Total threats detected: {summary.total_threats_detected}", ln=True)
    pdf.cell(0, 8, f"Total alerts: {summary.total_alerts}", ln=True)
    pdf.cell(0, 8, f"Total incidents: {summary.total_incidents}", ln=True)
    pdf.ln(3)
    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(0, 8, "Severity distribution:", ln=True)
    pdf.set_font("Helvetica", size=11)
    for sev, count in summary.severity_distribution.items():
        pdf.cell(0, 7, f"  {sev}: {count}", ln=True)

    out = bytes(pdf.output())
    log_action(db, user.id, "report_export_pdf", f"PDF report generated by '{user.username}'")
    return StreamingResponse(
        iter([out]), media_type="application/pdf",
        headers={"Content-Disposition": "attachment; filename=security_report.pdf"},
    )


@router.get("/audit", response_model=list[schemas.AuditLogOut])
def audit_logs(
    skip: int = 0, limit: int = 200, db: Session = Depends(get_db),
    admin: models.User = Depends(require_roles(models.UserRole.ADMIN)),
):
    return db.query(models.AuditLog).order_by(models.AuditLog.timestamp.desc()).offset(skip).limit(min(limit, 1000)).all()
